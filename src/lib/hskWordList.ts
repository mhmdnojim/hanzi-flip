/** Look up the HSK level for a Chinese word. Returns 1-6 or undefined. */
export function getHSKLevel(word: string): number | undefined {
  return HSK_DATA[word];
}

/** Count only CJK characters in a word. */
export function getCharacterCount(word: string): number {
  const cjk = word.match(/[\u4e00-\u9fff\u3400-\u4dbf]/g);
  return cjk ? cjk.length : 0;
}

/** Estimate frequency tier based on HSK level. */
export function getFrequencyTier(word: string): 'top500' | 'top1000' | 'rare' | 'unknown' {
  const level = getHSKLevel(word);
  if (!level) return 'unknown';
  if (level <= 2) return 'top500';
  if (level <= 3) return 'top1000';
  return 'rare';
}
